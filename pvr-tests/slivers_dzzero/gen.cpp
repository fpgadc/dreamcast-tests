/* Cases for slivers_dzzero: a zero depth (exponent field 0, any mantissa) in the mean of a determinant of zero.

       gen [--seed N]          ->  cases.h, cases.json (here)

   pvr-tests/slivers_dzspec: ((z1 + z2) + z3) * 1/3 on a console drops a depth of 2^-126 .. 2^-125 (exponent field 1)
   when the other corner of the first addition is a zero of the other sign, in some cases and not in others. Here
   that addition at its boundaries. Depth triples (z0, z1, z2), 4800 per set, two sets (gen.cpp of slivers_detzero's
   layout: cell by cell, row by row):
       kind 0  z0, z1 a zero (mantissa m) and a number of field 1 (fraction f), in either order, signs opposite; z2
               2^-123 .. 2^-120 so that the sum shows; 2f - m within 2^-6 .. 2^-23 of 1 or exactly 1 (the zero read as
               (1 + m) 2^-127 and taken off would leave exactly 2^-126)
       kind 1  the same with any f, m
       kind 2  the same with signs equal
       kind 3  a zero and a number of field 2 or 3, signs opposite
       kind 4  two zeros, then z2
       kind 5  the last addition: z0 of field 1, z1 a zero of its sign, z2 a zero of the other sign (or the same) with
               mantissa m2; only in cells 0 - 2 and 20 - 22, where the plane's zero slopes (2^-127 a pixel) are small
       kind 6  the last addition with z0 + z1 a number of field 1 made of two normal numbers, z2 a zero
   The sign of z2 (kinds 0-4): positive. */
#include <array>
#include "gen_common.h"

using namespace gen;

int main(int argc, char** argv)
{
    uint64_t seed = 1;
    for (int k = 1; k < argc; k++) {
        if (!strcmp(argv[k], "--seed") && k + 1 < argc) seed = strtoull(argv[++k], nullptr, 10);
        else Fail("gen [--seed N]");
    }
    Rng rng(seed);
    auto bits = [](bool neg, int field, uint32_t m) { return (neg ? 0x80000000u : 0u) | (uint32_t)field << 23 | (m & 0x7fffffu); };
    auto mant = [&]() { return (uint32_t)rng.integers(0, 1 << 23); };
    auto big = [&]() { return bits(false, (int)rng.integers(4, 8), mant()); };       // 2^-123 .. 2^-120
    std::vector<std::string> h;
    h.push_back("/* Generated by pvr-tests/slivers_dzzero/gen (gen.cpp) - do not edit. Floats are bit patterns. */");
    h.push_back("#include <stdint.h>");
    h.push_back("#define NUM_SETS 2");
    h.push_back("static const uint32_t tz[2][300 * 16][3] = { {     /* per set, cell by cell, row by row: z0, z1, z2 */");
    Json sets = Json::Array();
    int count[7] = { 0 };
    for (int s = 0; s < 2; s++) {
        Json js = Json::Array();
        std::string line;
        for (int i = 0; i < 4800; i++) {
            const int cell = i / 16;
            const bool nearOrigin = cell % 20 < 3 && cell / 20 < 2;
            int kind;
            if (nearOrigin) kind = rng.chance(0.75) ? 5 : 6;
            else {
                const double r = rng.uniform();
                kind = r < 0.45 ? 0 : r < 0.6 ? 1 : r < 0.75 ? 2 : r < 0.85 ? 3 : r < 0.92 ? 4 : 6;
            }
            uint32_t z[3];
            const bool negZero = rng.chance(0.5);
            switch (kind) {
            case 0: case 1: case 2: {
                uint32_t m = mant(), f = mant();
                if (kind == 0) {
                    // 2f - m = 1 + d (fractions of 2^23): f = (2^23 + m + d) / 2
                    const int64_t d = rng.chance(0.2) ? 0 : (rng.chance(0.5) ? 1 : -1) * (int64_t)rng.logUniform(1, 1 << 17);
                    int64_t ff = ((int64_t)(1 << 23) + m + d);
                    if (ff & 1) { if (m > 0) { m -= 1; ff -= 1; } else { m += 1; ff += 1; } }
                    ff /= 2;
                    if (ff < 0 || ff >= (1 << 23)) { i--; continue; }
                    f = (uint32_t)ff;
                }
                const bool other = kind == 2 ? negZero : !negZero;
                const uint32_t zero = bits(negZero, 0, m), num = bits(other, 1, f);
                const bool first = rng.chance(0.5);
                z[0] = first ? zero : num; z[1] = first ? num : zero; z[2] = big();
                break;
            }
            case 3: {
                const uint32_t zero = bits(negZero, 0, mant()), num = bits(!negZero, (int)rng.integers(2, 4), mant());
                const bool first = rng.chance(0.5);
                z[0] = first ? zero : num; z[1] = first ? num : zero; z[2] = big();
                break;
            }
            case 4:
                z[0] = bits(rng.chance(0.5), 0, mant()); z[1] = bits(rng.chance(0.5), 0, mant()); z[2] = big();
                break;
            case 5: {
                const bool neg = rng.chance(0.5);
                z[0] = bits(neg, 1, mant()); z[1] = bits(neg, 0, mant());
                z[2] = bits(rng.chance(0.8) ? !neg : neg, 0, mant());
                break;
            }
            default: {      // z0 + z1 of field 1 from two normal numbers (exact: same exponent, the difference)
                const bool neg = rng.chance(0.5);
                const uint32_t a = mant(), b = mant();
                // field 3 minus field 3 can land anywhere below; keep it simple: a field 2 and a field 1 of the other sign
                z[0] = bits(neg, 2, a); z[1] = bits(!neg, 1, b);
                z[2] = bits(rng.chance(0.7) ? !neg : neg, 0, mant());
                break;
            }
            }
            count[kind]++;
            line += Format("{0x%08xu,0x%08xu,0x%08xu},", z[0], z[1], z[2]);
            if (i % 8 == 7) { h.push_back("    " + line); line.clear(); }
            js.push(Json::Array().push((long long)z[0]).push((long long)z[1]).push((long long)z[2]).push(kind));
        }
        sets.push(js);
        h.push_back(s == 0 ? "}, {" : "} };");
    }
    WriteLines(Here() + "/cases.h", h);
    Json j = Json::Object();
    j.set("seed", (long long)seed);
    j.set("sets", sets);
    WriteFile(Here() + "/cases.json", j.dump() + "\n");
    fprintf(stderr, "kinds:");
    for (int k = 0; k < 7; k++) fprintf(stderr, " %d: %d", k, count[k]);
    fprintf(stderr, "\n");
    return 0;
}
