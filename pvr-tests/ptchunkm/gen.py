"""Configurations for ptchunkm: python3 gen.py [--seed N] [--pages N] > main.c's CONF (writes conf.h)."""
import random, sys
seed = int(sys.argv[sys.argv.index('--seed') + 1]) if '--seed' in sys.argv else 1
pages = int(sys.argv[sys.argv.index('--pages') + 1]) if '--pages' in sys.argv else 120
rng = random.Random(seed)
cost = {'t': 3, 'q': 4}
rows = []
while len(rows) < pages:
    S = rng.choice(list(range(0x20, 0x30)) + [0x40, 0x40, 0x40])
    a = rng.choice('tq')
    seq = []
    v = cost[a]
    target = rng.randint(S - 9, S + 1)            # the vertices before B end near the boundary
    while v < target:
        kind = rng.choice('ttqqs')
        if kind == 's':
            k = rng.randint(2, 6)
            seq.append(str(k)); v += 3 * k
        else:
            seq.append(kind); v += cost[kind]
    rows.append((S, a, ''.join(seq)))
with open(__file__.replace('gen.py', 'conf.h'), 'w') as f:
    f.write('/* Generated by gen.py --seed %d --pages %d: chunk size, A a sprite, the fillers between A and B (t a triangle, q a sprite,\n   2-6 a strip of that many triangles) */\n' % (seed, pages))
    f.write('#define NUM_CONF %d\nstatic const struct { int chunk, a_sprite; const char *fill; } CONF[NUM_CONF] = {\n' % len(rows))
    f.write(',\n'.join('    { 0x%02x, %d, "%s" }' % (S, a == 'q', s) for S, a, s in rows) + '\n};\n')
print(len(rows), 'configurations')
