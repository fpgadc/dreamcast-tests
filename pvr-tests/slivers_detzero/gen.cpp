/* Cases for slivers_detzero: the TSP's 1/w of a triangle whose determinant is zero, as a number (main.c).

       gen [--seed N]          ->  cases.h, cases.json (here)

   pvr-tests/slivers_tsp found it to be the mean of the corners' depths (not the third corner's, refsw3's guess). Here
   the arithmetic of that mean: every triangle is three equal corners (determinant exactly zero), drawn by the ISP
   on one row of its tile, and its three depths are picked so that ways of taking the mean differ in the 16 bits
   the TSP keeps of it:
       0  ((z0 + z1) + z2) * 1/3, the sums and the product cut to 24 bits, the reciprocal of 3 to 24 bits (the
          setup's arithmetic, as refsw3's ISP takes the mean of a zero determinant), then cut to 16
       1  ((z0 + z2) + z1) * 1/3        2  ((z1 + z2) + z0) * 1/3
       3  the exact mean, cut to 16     4  the sum times 0x5555 / 2^16 (1/3 in 16 bits)
       5  z0 / 3 + z1 / 3 + z2 / 3 (each product cut to 24 bits)
       6  the sum divided by 3 in the TSP's divider (its table reciprocal of 16 bits)
       7  the sum cut to 16 bits, then times 1/3
   A set: 8 pages of 300 cells, 16 triangles per cell (rows 0, 2, .. 30 of the tile, a corner at y = row + 1/4:
   the row range of three equal corners is that row alone; the ISP draws the tile's whole width there). Pages 0-3
   and 4-7 are two sets of 4800 triples, each read four ways (main.c). The depths: mean 1 .. 256 (so that the fog
   readout shows it), corners spread over up to 2^8 of each other with full 24 bit mantissas. Half of a set's
   triples are where some way differs from way 0 (chosen first for the rarer pairs), the rest random. */
#include "gen_common.h"
#include "pvr_tsp_plane.h"

using namespace gen;
using pvrfp::Fp;

static const int WAYS = 8, PAGES = 8, ROWS = 16;

static Fp Way(int w, const Fp z[3])
{
    using namespace pvrfp;
    auto add = [](const Fp& p, const Fp& q) { return Add(p, q, 24, 25); };
    auto sum3 = [&](int i, int j, int k) { return add(add(z[i], z[j]), z[k]); };
    const Fp third = Recip(Fp::FromHalves(6), 24);
    Fp r;
    switch (w) {
    case 0: r = Mul(sum3(0, 1, 2), third, 24); break;
    case 1: r = Mul(sum3(0, 2, 1), third, 24); break;
    case 2: r = Mul(sum3(1, 2, 0), third, 24); break;
    case 3: {
        Fp s = Add(Add(z[0], z[1], 62, 400), z[2], 62, 400);
        // floor(s / 3) to 16 bits: s has at most ~40 bits
        Fp q = s; q.mant <<= 20; q.exp -= 20;
        q.mant /= 3;
        r = q;
        break;
    }
    case 4: { Fp k; k.mant = 0x5555; k.exp = -16; r = Mul(sum3(0, 1, 2), k, 24); break; }
    case 5: r = add(add(Mul(z[0], third, 24), Mul(z[1], third, 24)), Mul(z[2], third, 24)); break;
    case 6: r = pvrtsp::Divide(sum3(0, 1, 2).cut(16), Fp::FromHalves(6)); break;
    case 7: r = Mul(sum3(0, 1, 2).cut(16), third, 24); break;
    }
    return r.cut(16);
}

static bool Same(const Fp& a, const Fp& b) { return a.toDouble() == b.toDouble(); }

int main(int argc, char** argv)
{
    uint64_t seed = 1;
    for (int k = 1; k < argc; k++) {
        if (!strcmp(argv[k], "--seed") && k + 1 < argc) seed = strtoull(argv[++k], nullptr, 10);
        else Fail("gen [--seed N]");
    }
    Rng rng(seed);
    struct Triple { uint32_t z[3]; unsigned diff; };
    // a random triple: z0 with mean-ish size, the others within 2^-8 .. 2^8 of it
    auto draw = [&]() {
        Triple t;
        for (;;) {
            const double base = rng.logUniform(1.0, 200.0);
            double z[3];
            for (int k = 0; k < 3; k++) {
                const double f = rng.logUniform(1.0 / 256, 256.0);
                z[k] = F32(base * f);
            }
            const double m = (z[0] + z[1] + z[2]) / 3;
            if (m < 1.0 || m >= 255.0)
                continue;
            Fp fz[3];
            for (int k = 0; k < 3; k++) {
                t.z[k] = Bits((float)z[k]);
                fz[k] = Fp::FromSingle(t.z[k], true);
            }
            const Fp w0 = Way(0, fz);
            t.diff = 0;
            for (int w = 1; w < WAYS; w++)
                if (!Same(Way(w, fz), w0))
                    t.diff |= 1u << w;
            return t;
        }
    };
    std::vector<std::string> h;
    h.push_back("/* Generated by pvr-tests/slivers_detzero/gen (gen.cpp) - do not edit. Floats are bit patterns. */");
    h.push_back("#include <stdint.h>");
    h.push_back(Format("#define NUM_SETS 2"));
    h.push_back("static const uint32_t tz[2][300 * 16][3] = {      /* per set, cell by cell, row by row: z0, z1, z2 */");
    Json sets = Json::Array();
    int counts[WAYS] = { 0 };
    for (int s = 0; s < 2; s++) {
        std::vector<Triple> pick;
        // first the rarer differences: for each way, triples where it differs from way 0
        std::vector<std::vector<Triple>> pool(WAYS);
        const int want = 4800 / 2 / (WAYS - 1);
        for (int n = 0; n < 4000000; n++) {
            Triple t = draw();
            for (int w = 1; w < WAYS; w++)
                if ((t.diff >> w & 1) && (int)pool[w].size() < want) {
                    pool[w].push_back(t);
                    break;
                }
            bool full = true;
            for (int w = 1; w < WAYS; w++)
                full = full && (int)pool[w].size() >= want;
            if (full) break;
        }
        for (int w = 1; w < WAYS; w++)
            pick.insert(pick.end(), pool[w].begin(), pool[w].end());
        while (pick.size() < 4800)
            pick.push_back(draw());
        // shuffled, so that a kind is not one region of the screen
        const std::vector<int> perm = rng.permutation(4800);
        Json js = Json::Array();
        std::string line;
        for (int i = 0; i < 4800; i++) {
            const Triple& t = pick[perm[i]];
            for (int w = 1; w < WAYS; w++)
                counts[w] += t.diff >> w & 1;
            line += Format("{0x%08xu,0x%08xu,0x%08xu},", t.z[0], t.z[1], t.z[2]);
            if (i % 8 == 7) { h.push_back("    " + line); line.clear(); }
            js.push(Json::Array().push((long long)t.z[0]).push((long long)t.z[1]).push((long long)t.z[2]).push((long long)t.diff));
        }
        sets.push(js);
        h.push_back(s == 0 ? "}, {" : "} };");
    }
    h[3] = "static const uint32_t tz[2][300 * 16][3] = { {     /* per set, cell by cell, row by row: z0, z1, z2 */";
    WriteLines(Here() + "/cases.h", h);
    Json j = Json::Object();
    j.set("seed", (long long)seed);
    j.set("sets", sets);
    WriteFile(Here() + "/cases.json", j.dump() + "\n");
    fprintf(stderr, "triples where way k differs from way 0:");
    for (int w = 1; w < WAYS; w++) fprintf(stderr, " %d: %d", w, counts[w]);
    fprintf(stderr, "\n");
    return 0;
}
