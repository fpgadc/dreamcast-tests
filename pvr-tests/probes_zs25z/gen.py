"""cases.h of dreamcast-tests/pvr-tests/probes_zs25z: the zs25 slivers (pvr-tests/covmeas, seed 25, mix sliver, the
triangles of every zs25* / zs25f_* set) and the tiles whose depths it reads out.

    python3 gen.py <covmeas cases.h of a zs25 set (run2.sh covmeas@zs25f_e4 off writes one)> <tiles.txt> <out cases.h>

tiles.txt (this folder): lines "page tx ty" (the tiles of the pixels covprobe missed on zs25_005, zs25f_01, zs25f_e2, zs25f_e4),
plus the control tiles named below."""
import re
import sys

src, tiles_txt, out = sys.argv[1:4]
text = open(src).read()
tris = re.findall(r"\{ (\d+), \{ \{ (0x[0-9a-f]+)u, (0x[0-9a-f]+)u \}, \{ (0x[0-9a-f]+)u, (0x[0-9a-f]+)u \}, \{ (0x[0-9a-f]+)u, (0x[0-9a-f]+)u \}", text)
assert len(tris) == 2400, len(tris)
zs = re.search(r"#define COV_ZS (\{[^}]*\})", text).group(1)
assert zs == "{ 0x3e4ccccdu, 0x3f333333u, 0x3e99999au }", zs
tiles = sorted({tuple(int(v) for v in l.split()) for l in open(tiles_txt) if l.strip()})
lines = ["/* Generated by pvr-tests/probes_zs25z/gen.py - do not edit. Floats are bit patterns. */",
         "#include <stdint.h>",
         "#define NUM_TRIS 2400",
         f"#define ZS_ZS {zs}           /* 0.2, 0.7, 0.3 */",
         "typedef struct { unsigned char page; uint32_t v[3][2]; } tri_t;",
         "static const tri_t tris[NUM_TRIS] = {"]
for t in tris:
    lines.append("    { %s, { { %su, %su }, { %su, %su }, { %su, %su } } }," % t)
lines += ["};", f"#define NUM_TILES {len(tiles)}",
          "static const struct { unsigned char page, x, y; } tiles[NUM_TILES] = {"]
for p, x, y in tiles:
    lines.append(f"    {{ {p}, {x}, {y} }},")
lines.append("};")
open(out, "w").write("\n".join(lines) + "\n")
print(f"{len(tris)} triangles, {len(tiles)} tiles -> {out}")
