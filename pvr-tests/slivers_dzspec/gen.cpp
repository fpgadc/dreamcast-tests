/* Cases for slivers_dzspec: the mean of a determinant of zero (slivers_detzero) at the limits of the setup's numbers,
   and table fog over a 1/w below zero (main.c).

       gen [--seed N]          ->  cases.h, cases.json (here)

   tz[0]: 4800 depth triples for determinant-zero points, one kind per triple (random):
       0  one corner below zero, the mean above            1  the mean below zero (two or three corners below)
       2  an exact cancellation: a, -a, 0 or a, b, -(a + b)
       3  one corner +0, -0 or denormal (a zero to the setup), the others ordinary
       4  huge: corners 2^125 .. 2^128 (the sum may overflow)
       5  tiny: corners 2^-127 .. 2^-120 (the mean may fall below 2^-126)
       6  one corner +-infinity or a NaN
       7  corners of very different size (2^-40 .. 2^40 of each other: the adder drops what is 25 exponents below)
   tz[1]: 4800 flat depths (all three corners) for triangles of determinant 12: below zero (-2^-8 .. -2^8, random
   mantissas), +-0, +-inf, NaN, and above zero. */
#include <array>
#include "gen_common.h"

using namespace gen;

int main(int argc, char** argv)
{
    uint64_t seed = 1;
    for (int k = 1; k < argc; k++) {
        if (!strcmp(argv[k], "--seed") && k + 1 < argc) seed = strtoull(argv[++k], nullptr, 10);
        else Fail("gen [--seed N]");
    }
    Rng rng(seed);
    auto mant = [&]() { return (uint32_t)rng.integers(0, 1 << 23); };
    auto num = [&](int e, bool neg) { return (neg ? 0x80000000u : 0u) | (uint32_t)(e + 127) << 23 | mant(); };      // [2^e, 2^(e+1))
    auto pos = [&](double lo, double hi) { return Bits((float)rng.logUniform(lo, hi)); };
    std::vector<std::array<uint32_t, 4>> a;             // z0, z1, z2, kind
    for (int i = 0; i < 4800; i++) {
        const int kind = (int)rng.integers(0, 8);
        uint32_t z[3];
        switch (kind) {
        case 0: {
            const double p = rng.logUniform(1, 50), q = rng.logUniform(1, 50), r = rng.uniform(0.05, 0.95) * (p + q);
            z[0] = Bits((float)p); z[1] = Bits((float)q); z[2] = Bits((float)-r);
            break;
        }
        case 1: {
            const bool three = rng.chance(0.5);
            const double p = rng.logUniform(1, 50), q = rng.logUniform(1, 50);
            const double r = three ? rng.logUniform(1, 50) : rng.uniform(0.05, 0.95) * (p + q);
            z[0] = Bits((float)-p); z[1] = Bits((float)-q); z[2] = Bits((float)(three ? -r : r));
            break;
        }
        case 2: {
            if (rng.chance(0.5)) {
                const uint32_t v = pos(0.5, 100);
                z[0] = v; z[1] = v ^ 0x80000000u; z[2] = rng.chance(0.5) ? 0u : 0x80000000u;
            } else {        // a, b on a coarse grid so that a + b is exact
                const double p = (double)rng.integers(1, 4096) / 64, q = (double)rng.integers(1, 4096) / 64;
                z[0] = Bits((float)p); z[1] = Bits((float)q); z[2] = Bits((float)-(p + q));
            }
            break;
        }
        case 3: {
            const int w = (int)rng.integers(0, 3);
            z[0] = w == 0 ? 0u : w == 1 ? 0x80000000u : (uint32_t)rng.integers(1, 1 << 23);
            z[1] = pos(0.25, 100); z[2] = pos(0.25, 100);
            break;
        }
        case 4:
            for (uint32_t& v : z) v = num((int)rng.integers(125, 128), false);
            break;
        case 5:
            for (uint32_t& v : z) v = num((int)rng.integers(-127, -120), rng.chance(0.2));
            break;
        case 6: {
            static const uint32_t special[5] = { 0x7f800000u, 0xff800000u, 0x7fc00000u, 0xffc00000u, 0x7f800001u };
            z[0] = special[rng.integers(0, 5)]; z[1] = pos(0.25, 100); z[2] = pos(0.25, 100);
            break;
        }
        default: {
            const int e0 = (int)rng.integers(-10, 10);
            for (uint32_t& v : z) {
                const int e = e0 + (int)rng.integers(-40, 41);
                v = num(e, false);
            }
            break;
        }
        }
        // the special corner at a random place
        const std::vector<int> perm = rng.permutation(3);
        a.push_back({ z[perm[0]], z[perm[1]], z[perm[2]], (uint32_t)kind });
    }
    std::vector<uint32_t> flat;
    for (int i = 0; i < 4800; i++) {
        const int kind = (int)rng.integers(0, 10);
        static const uint32_t special[6] = { 0u, 0x80000000u, 0x7f800000u, 0xff800000u, 0x7fc00000u, 0xffc00000u };
        uint32_t v;
        if (kind < 6) v = num((int)rng.integers(-8, 9), true);
        else if (kind < 8) v = num((int)rng.integers(-8, 9), false);
        else v = special[rng.integers(0, 6)];
        flat.push_back(v);
    }
    std::vector<std::string> h;
    h.push_back("/* Generated by pvr-tests/slivers_dzspec/gen (gen.cpp) - do not edit. Floats are bit patterns. */");
    h.push_back("#include <stdint.h>");
    h.push_back("static const uint32_t tz[4800][3] = {     /* determinant zero: cell by cell, row by row: z0, z1, z2 */");
    std::string line;
    for (int i = 0; i < 4800; i++) {
        line += Format("{0x%08xu,0x%08xu,0x%08xu},", a[i][0], a[i][1], a[i][2]);
        if (i % 8 == 7) { h.push_back("    " + line); line.clear(); }
    }
    h.push_back("};");
    h.push_back("static const uint32_t zflat[4800] = {     /* determinant 12: one depth for all three corners */");
    for (int i = 0; i < 4800; i++) {
        line += Format("0x%08xu,", flat[i]);
        if (i % 12 == 11) { h.push_back("    " + line); line.clear(); }
    }
    h.push_back("};");
    WriteLines(Here() + "/cases.h", h);
    Json j = Json::Object(), ja = Json::Array(), jf = Json::Array();
    for (auto& t : a) ja.push(Json::Array().push((long long)t[0]).push((long long)t[1]).push((long long)t[2]).push((long long)t[3]));
    for (auto v : flat) jf.push((long long)v);
    j.set("seed", (long long)seed);
    j.set("detzero", ja);
    j.set("flat", jf);
    WriteFile(Here() + "/cases.json", j.dump() + "\n");
    return 0;
}
