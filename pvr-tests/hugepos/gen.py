"""hugepos: which triangle and which exponents.

    python gen.py [--tri all|a|b|c] [m0 m1 ... (16 values)]   ->  cases.h, cases.json

--tri all: the three triangles together in the translucent list, one color channel each (blend ONE, ONE).
--tri a / b / c: one of them alone, white, in the opaque list.
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).parent
args = sys.argv[1:]
tri = "all"
if args and args[0] == "--tri":
    tri = args[1]
    args = args[2:]
ms = [int(a) for a in args] or [30, 60, 98, 102, 104, 106, 108, 110, 112, 114, 116, 118, 120, 122, 124, 125]
assert len(ms) == 16 and max(ms) <= 125 and tri in ("all", "a", "b", "c")
(HERE / "cases.h").write_bytes(("/* Generated by gen.py - do not edit. */\n#define HP_TRI %d\nstatic const int ms[16] = { %s };\n"
                               % (["all", "a", "b", "c"].index(tri), ", ".join(str(m) for m in ms))).encode())
(HERE / "cases.json").write_text(json.dumps({"ms": ms, "tri": tri}))
print("triangle", tri, "exponents", ms)
