/* trimin's cases (pvr-tests/trimin/main.c): the u slope of a flat quad (1/w = 1, u along x only) that gives the
   mipmap level L and fraction f (of 128) wanted, as the model has them (pvrtsp::MipSelect, refsw3-core
   pvr_tsp_plane.h; measured with pvr-tests/mipmeas). The smallest float slope whose (L, f) is at least the target
   is taken, and both triangles of the quad must give the same.
   Build: bash model/build.sh trimin; run: pvr-tests/trimin/gen -> pvr-tests/trimin/cases.h */
#include "gen_common.h"

using namespace gen;

static const int SIZES[2] = { 3, 6 };          // log2 of the texture's size: 8 x 8 (TexU 0), 64 x 64 (TexU 3)
static const int COLS = 10;

// the cell's quad: corners TL, TR, BL, BR at (x, y) .. (x + 32, y + 32), u = su X (X = 0 .. 32), v a quarter
// texel, 1/w = 1; the model's level and fraction of each of its two triangles
static bool Choose(const Model& m, int sizeLog2, int x, int y, float su, int* L, int* f)
{
    const float cx[4] = { (float)x, (float)(x + 32), (float)x, (float)(x + 32) };
    const float cy[4] = { (float)y, (float)y, (float)(y + 32), (float)(y + 32) };
    const float cu[4] = { 0, su * 32, 0, su * 32 };
    const float v = 1.0f / (float)(4 << sizeLog2);
    int got[2][2];
    for (int t = 0; t < 2; t++) {
        const float fx[3] = { cx[t], cx[t + 1], cx[t + 2] }, fy[3] = { cy[t], cy[t + 1], cy[t + 2] };
        const float fz[3] = { 1, 1, 1 }, fu[3] = { cu[t], cu[t + 1], cu[t + 2] }, fv[3] = { v, v, v };
        pvrtsp::Plane pu, pv, pw;
        pu.Setup(F32s(fx), F32s(fy), F32s(fz), F32s(fu), m.plane);
        pv.Setup(F32s(fx), F32s(fy), F32s(fz), F32s(fv), m.plane);
        pw.Setup(F32s(fx), F32s(fy), F32s(fz), nullptr, m.plane);
        const pvrtsp::MipChoice c = pvrtsp::MipSelect(pu, pv, pw, pvrfp::Fp::FromFloat(1.0f), sizeLog2, 4);
        got[t][0] = c.level;
        got[t][1] = c.k == 256 ? 127 : c.k / 2;
    }
    *L = got[0][0]; *f = got[0][1];
    return got[0][0] == got[1][0] && got[0][1] == got[1][1];
}

int main()
{
    Model model;
    std::vector<std::string> out;
    out.push_back("/* Generated by pvr-tests/trimin/gen (gen.cpp) - do not edit. SU: the u slope a pixel (float bits) of column c");
    out.push_back("   of texture t (0: 8 x 8, 1: 64 x 64); LEV, FRAC: the model's level and fraction (of 128) there. */");
    out.push_back("static const uint32_t SU[2][10] = {");
    std::vector<std::string> lev, frac;
    for (int t = 0; t < 2; t++) {
        const int top = SIZES[t];
        const int target[COLS][2] = { { top - 1, 64 }, { top, 0 }, { top, 64 }, { top, 127 }, { top + 1, 0 },
                                      { top + 1, 64 }, { top + 2, 64 }, { 11, 64 }, { 12, 64 }, { 20, 64 } };
        std::string su = "    {", ls = "    {", fs = "    {";
        for (int c = 0; c < COLS; c++) {
            const int want = target[c][0] * 256 + 128 + target[c][1];
            // the floats are ordered as their bits: the first whose (L, m) is at least the target
            uint32_t lo = Bits(ldexpf(1, -12)), hi = Bits(ldexpf(1, 26));
            while (lo < hi) {
                const uint32_t mid = lo + (hi - lo) / 2;
                int L, f;
                Choose(model, top, 0, 0, FromBits(mid), &L, &f);
                if (L * 256 + 128 + f >= want) hi = mid; else lo = mid + 1;
            }
            // and placed in its cell (column c + 10 t, every row): every row's quad must give the same
            int L = 0, f = 0;
            for (int row = 0; row < 15; row++) {
                int Lr, fr;
                if (!Choose(model, top, 32 * (c + 10 * t), 32 * row, FromBits(lo), &Lr, &fr))
                    Fail(Format("texture %d column %d row %d: the two triangles differ", t, c, row));
                if (row && (Lr != L || fr != f))
                    Fail(Format("texture %d column %d row %d: (%d, %d), row 0 (%d, %d)", t, c, row, Lr, fr, L, f));
                L = Lr; f = fr;
            }
            printf("texture %d column %2d: want (%2d, %3d), slope %08x %.9g: (%2d, %3d)\n", t, c, target[c][0], target[c][1],
                   lo, FromBits(lo), L, f);
            su += Format(" 0x%08xu,", lo);
            ls += Format(" %d,", L);
            fs += Format(" %d,", f);
        }
        out.push_back(su + " },");
        lev.push_back(ls + " },");
        frac.push_back(fs + " },");
    }
    out.push_back("};");
    out.push_back("static const int LEV[2][10] = {");
    for (auto& s : lev) out.push_back(s);
    out.push_back("};");
    out.push_back("static const int FRAC[2][10] = {");
    for (auto& s : frac) out.push_back(s);
    out.push_back("};");
    WriteLines(Here() + "/cases.h", out);
    return 0;
}
