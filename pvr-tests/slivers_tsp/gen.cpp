/* Cases for slivers_tsp: covmeas's slivers, almost-points and degenerate triangles, each given a depth, a U and a
   colour per corner, drawn on three pages: read as U, as 1/w and as colour (main.c).

       gen [--seed N] [--group <covmeas set>:<page>:<style>]...      ->  cases.h, cases.json (here)
       gen --regen <set>.cases.json <folder>                           ->  the tables of a set

   A group is the 300 triangles of one page of an archived covmeas set (fit/covmeas_data/<set>.cases.json: their
   corners as they were sent) with attributes of one style:
       var    each corner its own depth (2^-2 .. 2^2, log-uniform), U (64 .. 128: read through the texture to its
              last bit, uvmeas) and colour (each channel 0x20 .. 0xe0)
       flat   one depth, U and colour for all three corners of a triangle (a flat plane, of garbage slopes)
       zflat  one depth, U and colour per corner as var (only the 1/w plane is flat)
   Group g goes to pages 3 g (U), 3 g + 1 (1/w), 3 g + 2 (colour). Four groups; the default:
       sliver30:0:var tiny42:0:var degen40:0:var sliver30:1:flat */
#include "gen_common.h"

using namespace gen;

static const int GROUPS = 4, PAGES = 3 * GROUPS;

struct Tri {
    int page;
    uint32_t v[3][4];       // x, y, z, u
    uint32_t col[3];
    std::string group;
};

static void Write(const std::string& folder, const std::vector<Tri>& tris, const std::vector<std::string>& what, const Json& args)
{
    std::vector<std::string> h;
    h.push_back("/* Generated by pvr-tests/slivers_tsp/gen (gen.cpp) - do not edit. Floats are bit patterns. */");
    h.push_back("#include <stdint.h>");
    h.push_back(Format("#define NUM_TRIS %zu", tris.size()));
    std::string modes = "static const unsigned char PAGE_MODE[12] = { ", names = "static const char *const PAGE_WHAT[12] = { ";
    for (int p = 0; p < PAGES; p++) {
        modes += Format("%d%s", p % 3, p + 1 < PAGES ? ", " : " };");
        names += "\"" + what[p / 3] + "\"" + (p + 1 < PAGES ? ", " : " };");
    }
    h.push_back(modes);
    h.push_back(names);
    h.push_back("typedef struct { unsigned char page; uint32_t v[3][4]; uint32_t col[3]; } tri_t;   /* x, y, z, u; ARGB */");
    h.push_back("static const tri_t tris[NUM_TRIS] = {");
    for (const Tri& t : tris) {
        std::string s = Format("    { %d, { ", t.page);
        for (int k = 0; k < 3; k++)
            s += Format("{ 0x%08xu, 0x%08xu, 0x%08xu, 0x%08xu }%s", t.v[k][0], t.v[k][1], t.v[k][2], t.v[k][3], k < 2 ? ", " : " }, ");
        s += Format("{ 0x%08xu, 0x%08xu, 0x%08xu } },", t.col[0], t.col[1], t.col[2]);
        h.push_back(s);
    }
    h.push_back("};");
    WriteLines(folder + "/cases.h", h);

    Json j = args;
    Json pages = Json::Array();
    for (int p = 0; p < PAGES; p++) {
        Json list = Json::Array();
        for (const Tri& t : tris) {
            if (t.page != p)
                continue;
            Json e = Json::Object();
            for (int c = 0; c < 4; c++) {
                static const char* const key[4] = { "x", "y", "z", "u" };
                Json a = Json::Array();
                for (int k = 0; k < 3; k++)
                    a.push((long long)t.v[k][c]);
                e.set(key[c], a);
            }
            e.set("col", Json::Array().push((long long)t.col[0]).push((long long)t.col[1]).push((long long)t.col[2]));
            e.set("group", t.group);
            list.push(e);
        }
        pages.push(list);
    }
    Json w = Json::Array();
    for (auto& s : what)
        w.push(s);
    j.set("what", w);
    j.set("pages", pages);
    WriteFile(folder + "/cases.json", j.dump() + "\n");
}

int main(int argc, char** argv)
{
    std::vector<std::string> a(argv + 1, argv + argc);
    if (a.size() == 3 && a[0] == "--regen") {           // the bits are in the set itself
        const Json j = Json::Parse(ReadFile(a[1]));
        std::vector<Tri> tris;
        const Json& pages = j.at("pages");
        for (size_t p = 0; p < pages.size(); p++)
            for (size_t i = 0; i < pages[p].size(); i++) {
                const Json& e = pages[p][i];
                Tri t;
                t.page = (int)p;
                static const char* const key[4] = { "x", "y", "z", "u" };
                for (int c = 0; c < 4; c++)
                    for (int k = 0; k < 3; k++)
                        t.v[k][c] = (uint32_t)e.at(key[c])[k].integer();
                for (int k = 0; k < 3; k++)
                    t.col[k] = (uint32_t)e.at("col")[k].integer();
                t.group = e.at("group").str();
                tris.push_back(t);
            }
        std::vector<std::string> what;
        for (size_t k = 0; k < j.at("what").size(); k++)
            what.push_back(j.at("what")[k].str());
        Json args = Json::Object();
        args.set("seed", j.at("seed"));
        args.set("groups", j.at("groups"));
        Write(a[2], tris, what, args);
        return 0;
    }
    uint64_t seed = 1;
    std::vector<std::string> groups;
    for (size_t k = 0; k < a.size(); k++) {
        if (a[k] == "--seed" && k + 1 < a.size()) seed = strtoull(a[++k].c_str(), nullptr, 10);
        else if (a[k] == "--group" && k + 1 < a.size()) groups.push_back(a[++k]);
        else Fail("gen [--seed N] [--group <covmeas set>:<page>:var|flat|zflat]...  |  gen --regen <set>.cases.json <folder>");
    }
    if (groups.empty())
        groups = { "sliver30:0:var", "tiny42:0:var", "degen40:0:var", "sliver30:1:flat" };
    if ((int)groups.size() != GROUPS)
        Fail("four groups");
    Rng rng(seed);
    std::vector<Tri> tris;
    std::vector<std::string> what;
    Json gl = Json::Array();
    for (int g = 0; g < GROUPS; g++) {
        const std::string& spec = groups[g];
        const size_t c1 = spec.find(':'), c2 = spec.find(':', c1 + 1);
        if (c1 == std::string::npos || c2 == std::string::npos)
            Fail("a group is <set>:<page>:<style>");
        const std::string set = spec.substr(0, c1), style = spec.substr(c2 + 1);
        const int page = atoi(spec.substr(c1 + 1, c2 - c1 - 1).c_str());
        if (style != "var" && style != "flat" && style != "zflat")
            Fail("style: var, flat or zflat");
        gl.push(spec);
        what.push_back(set + " page " + std::to_string(page) + ", " + style);
        const Json src = Json::Parse(ReadFile(Here() + "/../../fit/covmeas_data/" + set + ".cases.json"));
        const Json& list = src.at("pages")[page];
        for (size_t i = 0; i < list.size(); i++) {
            const Json& e = list[i];
            if (e.at("x").size() != 3)
                Fail(set + ": not triangles");
            double z[3], u[3];
            uint32_t col[3];
            for (int k = 0; k < 3; k++) {
                z[k] = F32(rng.logUniform(0.25, 4.0));
                u[k] = F32(rng.uniform(64.0, 128.0));
                uint32_t c = 0xff000000u;
                for (int ch = 0; ch < 3; ch++) {
                    const int64_t v = rng.integers(0x20, 0xe1);
                    c |= (uint32_t)v << (8 * ch);
                }
                col[k] = c;
            }
            for (int k = 1; k < 3; k++) {
                if (style != "var")
                    z[k] = z[0];
                if (style == "flat") {
                    u[k] = u[0];
                    col[k] = col[0];
                }
            }
            for (int m = 0; m < 3; m++) {
                Tri t;
                t.page = 3 * g + m;
                for (int k = 0; k < 3; k++) {
                    t.v[k][0] = Bits((float)e.at("x")[k].num());
                    t.v[k][1] = Bits((float)e.at("y")[k].num());
                    t.v[k][2] = Bits((float)z[k]);
                    t.v[k][3] = Bits((float)u[k]);
                    t.col[k] = col[k];
                }
                t.group = e.at("group").str();
                tris.push_back(t);
            }
        }
    }
    std::stable_sort(tris.begin(), tris.end(), [](const Tri& p, const Tri& q) { return p.page < q.page; });
    Json args = Json::Object();
    args.set("seed", (long long)seed);
    args.set("groups", gl);
    Write(Here(), tris, what, args);
    fprintf(stderr, "%zu triangles on %d pages\n", tris.size(), PAGES);
    return 0;
}
