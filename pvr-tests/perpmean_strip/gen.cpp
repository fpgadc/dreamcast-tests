/* The strips and sprites of pvr-tests/perpmean_strip (main.c says what the test does). Writes cases.h next to this
   file.
       g++ -O2 -o gen gen.cpp && ./gen [seed]
   Floats are bit patterns. Per pixel: a target of three corners (a strip's last triangle: the corners P, Q, R of the
   cell in one of six orders; a sprite: three corners of the cell's square in one of eight orders), the depths of
   the target's three corners in the order sent, and the decoy corners before them (a strip's earlier triangles,
   beyond the target's first edge: they cover no pixel center). Three in four triples are chosen so that the three
   possible last terms of the mean's sum, (a + b) + c, do not all give the same stored word (perpmean_word's rule;
   about 1 % of random triples);
   every exact mean is positive and within 2^-90 .. 2^90 (zexfil.h). */
#include <cstdio>
#include <cstdint>
#include <cstdlib>
#include <cstring>
#include <string>
#include <vector>

static uint64_t S = 0x2545F4914F6CDD1Dull;
static uint32_t rnd() { S ^= S << 13; S ^= S >> 7; S ^= S << 17; return (uint32_t)(S >> 16); }
static int irange(int lo, int hi) { return lo + (int)(rnd() % (uint32_t)(hi - lo + 1)); }
static uint32_t F(int e, uint32_t m, bool neg = false) { return (neg ? 0x80000000u : 0) | (uint32_t)(e + 127) << 23 | (m & 0x7fffff); }
static uint32_t R(int e) { return F(e, 0x800000u | (rnd() & 0x7fffff)); }

/* perpmean_word's rule, positive results only: sum in the setup's adder (24 bits toward zero, an operand 25
   binades below the other dropped), divided by 3 toward zero, cut to 20 then 19 bits */
typedef unsigned __int128 U;
struct X { bool neg = false; U m = 0; int e = 0; };
static int bl(U v) { int n = 0; while (v) { v >>= 1; n++; } return n; }
static X Ld(uint32_t u) { X r; r.neg = u >> 31; uint32_t f = (u >> 23) & 255; if (!f) return r; r.m = (u & 0x7fffff) | 0x800000; r.e = (int)f - 150; return r; }
static X Cut(X x, int b) { int n = bl(x.m); if (n > b) { x.m >>= n - b; x.e += n - b; } return x; }
static X Add(X a, X b)
{
    if (!a.m) return b;
    if (!b.m) return a;
    int ta = a.e + bl(a.m), tb = b.e + bl(b.m);
    if (ta - tb >= 25) return a;
    if (tb - ta >= 25) return b;
    int e = a.e < b.e ? a.e : b.e;
    U ma = a.m << (a.e - e), mb = b.m << (b.e - e);
    X r; r.e = e;
    if (a.neg == b.neg) { r.m = ma + mb; r.neg = a.neg; }
    else if (ma >= mb) { r.m = ma - mb; r.neg = a.neg; }
    else { r.m = mb - ma; r.neg = b.neg; }
    if (!r.m) r.neg = false;
    return Cut(r, 24);
}
static uint32_t Mean(uint32_t a, uint32_t b, uint32_t c)
{
    X s = Add(Add(Ld(a), Ld(b)), Ld(c));
    if (!s.m || s.neg) return 0xffffffffu;
    X q; q.m = (s.m << 40) / 3; q.e = s.e - 40;
    q = Cut(Cut(q, 20), 19);
    int n = bl(q.m), top = q.e + n;
    if (top - 1 < -90 || top - 1 > 90) return 0xffffffffu;
    return (uint32_t)(top - 1 + 127) << 23 | (uint32_t)((q.m << (24 - n)) & 0x7fffff);
}

/* cell corners in 1/16 pixel: P, Q, R (the target triangle), the square's fourth corner S for sprites */
static const int CP[4][2] = { {4, 4}, {16, 4}, {4, 16}, {16, 16} };
static const int PERM[6][3] = { {0, 1, 2}, {0, 2, 1}, {1, 0, 2}, {1, 2, 0}, {2, 0, 1}, {2, 1, 0} };
/* decoys beyond each edge of PQR: edge PQ (y < 4), PR (x < 4), QR (x + y > 20) */
static const int DEC[3][5][2] = {
    { {10, 0}, {2, 1}, {14, 2}, {6, 0}, {12, 3} },
    { {0, 10}, {1, 2}, {2, 14}, {0, 6}, {3, 12} },
    { {16, 16}, {12, 15}, {16, 10}, {9, 16}, {15, 13} },
};
static long long cross(const int* a, const int* b, const int* c) { return (long long)(b[0] - a[0]) * (c[1] - a[1]) - (long long)(b[1] - a[1]) * (c[0] - a[0]); }
static bool inside(const int* a, const int* b, const int* c, int x, int y)   /* strictly or on an edge */
{
    int p[2] = { x, y };
    long long d1 = cross(a, b, p), d2 = cross(b, c, p), d3 = cross(c, a, p);
    bool hasNeg = d1 < 0 || d2 < 0 || d3 < 0, hasPos = d1 > 0 || d2 > 0 || d3 > 0;
    return !(hasNeg && hasPos);
}

struct Tile { int tx, ty, kind, len, pos; const char* name; };     // kind 0 strip, 1 sprite
static const Tile T[] = {
    { 3, 2, 0, 6, 1, "strip of 6 a entry, target at triangle 1" },
    { 5, 2, 0, 6, 2, "strip of 6 a entry, target at triangle 2" },
    { 7, 2, 0, 6, 3, "strip of 6 a entry, target at triangle 3" },
    { 9, 2, 0, 6, 5, "strip of 6 a entry, target at triangle 5" },
    { 3, 4, 0, 1, 1, "strip of 1 a entry, target at triangle 1" },
    { 5, 4, 0, 2, 3, "strip of 2 a entry, target at triangle 3" },
    { 7, 4, 1, 0, 0, "sprites, eight corner orders" },
    { 9, 4, 1, 0, 0, "sprites, eight corner orders (other depths)" },
};
#define NT (int)(sizeof(T) / sizeof(T[0]))

int main(int argc, char** argv)
{
    if (argc > 1) S ^= strtoull(argv[1], 0, 0) * 0x9e3779b97f4a7c15ull;
    FILE* f = fopen((std::string(argc > 2 ? argv[2] : ".") + "/cases.h").c_str(), "w");
    fprintf(f, "/* Generated by pvr-tests/perpmean_strip/gen (gen.cpp) - do not edit. Floats are bit patterns; corners in 1/16\n   pixel from the pixel's top left. */\n");
    fprintf(f, "#define NT %d\n", NT);
    fprintf(f, "static const struct { unsigned char tx, ty, kind, len, pos; const char *name; } tiles[NT] = {\n");
    for (int t = 0; t < NT; t++) fprintf(f, "    { %d, %d, %d, %d, %d, \"%s\" },\n", T[t].tx, T[t].ty, T[t].kind, T[t].len, T[t].pos, T[t].name);
    fprintf(f, "};\n/* per tile, per pixel (row by row): the vertices in the order sent (x, y in 1/16 pixel), nv of them; the\n   target's three are the last three (a sprite: A, B, C, then D) */\n");
    fprintf(f, "typedef struct { unsigned char nv, ord; unsigned char xy[8][2]; uint32_t z[3]; } cell_t;\n");
    fprintf(f, "static const cell_t cells[NT][1024] = {\n");
    for (int t = 0; t < NT; t++) {
        fprintf(f, "  {\n");
        for (int k = 0; k < 1024; k++) {
            int xy[8][2], nv = 0, ord;
            if (T[t].kind == 0) {
                ord = (int)(rnd() % 6);
                const int* v0 = CP[PERM[ord][0]];
                const int* v1 = CP[PERM[ord][1]];
                const int* v2 = CP[PERM[ord][2]];
                int a = PERM[ord][0], b = PERM[ord][1];
                int edge = (a + b == 1) ? 0 : (a + b == 2) ? 1 : 2;       // PQ, PR, QR
                for (int d = T[t].pos - 1; d >= 0; d--) { xy[nv][0] = DEC[edge][d][0]; xy[nv][1] = DEC[edge][d][1]; nv++; }
                xy[nv][0] = v0[0]; xy[nv][1] = v0[1]; nv++;
                xy[nv][0] = v1[0]; xy[nv][1] = v1[1]; nv++;
                xy[nv][0] = v2[0]; xy[nv][1] = v2[1]; nv++;
                for (int i = 0; i + 2 < nv; i++) {
                    if (cross(xy[i], xy[i + 1], xy[i + 2]) == 0) { fprintf(stderr, "degenerate t%d k%d i%d\n", t, k, i); return 1; }
                    bool cov = inside(xy[i], xy[i + 1], xy[i + 2], 8, 8);
                    if (cov != (i + 3 == nv)) { fprintf(stderr, "coverage t%d k%d i%d\n", t, k, i); return 1; }
                }
            } else {
                // the square P Q S R (clockwise on the screen from P); A at corner s, B, C the next ones, direction d
                static const int SQ[4] = { 0, 1, 3, 2 };
                int s = (int)(rnd() % 4), d = (int)(rnd() % 2);
                ord = s * 2 + d;
                for (int i = 0; i < 4; i++) {
                    const int* c = CP[SQ[(s + (d ? 4 - i : i)) % 4]];
                    xy[nv][0] = c[0]; xy[nv][1] = c[1]; nv++;
                }
            }
            uint32_t z[3];
            bool want = (k % 4) != 3;
            for (int tries = 0;; tries++) {
                int fam = (int)(rnd() % 3), e = irange(-6, 6);
                for (int i = 0; i < 3; i++) {
                    if (fam == 0) z[i] = R(e + irange(-12, 12));
                    else if (fam == 1) z[i] = R(i == (int)(k % 3) ? e - irange(16, 30) : e + irange(-1, 1));
                    else z[i] = R(e + irange(-3, 3));
                }
                uint32_t m0 = Mean(z[0], z[1], z[2]), m1 = Mean(z[0], z[2], z[1]), m2 = Mean(z[1], z[2], z[0]);
                if (m0 == 0xffffffffu || m1 == 0xffffffffu || m2 == 0xffffffffu) continue;
                if (!want || !(m0 == m1 && m1 == m2) || tries > 5000) break;
            }
            fprintf(f, "    { %d, %d, {", nv, ord);
            for (int i = 0; i < 8; i++) fprintf(f, "{%d,%d}%s", i < nv ? xy[i][0] : 0, i < nv ? xy[i][1] : 0, i < 7 ? "," : "");
            fprintf(f, "}, { 0x%08xu, 0x%08xu, 0x%08xu } },\n", z[0], z[1], z[2]);
        }
        fprintf(f, "  },\n");
    }
    fprintf(f, "};\n");
    fclose(f);
    return 0;
}
